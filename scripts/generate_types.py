"""Generate TypedDicts from the pinned engine documents. `--check` fails when the committed output is stale.

Rule: runtime code never imports meridian._generated outside `if TYPE_CHECKING:`; the generated modules need
typing_extensions, which is a dev-only dependency. The versions of datamodel-code-generator, black and isort are
pinned exactly in pyproject.toml so output cannot change silently.
"""

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'meridian' / '_generated'
PRICED = re.compile('cost|price|per_million', re.IGNORECASE)
PRICED_SCHEMA = re.compile('cost|price', re.IGNORECASE)
HEADER = (
    '# Generated by scripts/generate_types.py from spec/. Do not edit.\n'
    '# Type-checking only: import under `if TYPE_CHECKING:`, never at runtime (needs typing_extensions, dev-only).\n'
)


def without_priced(node: Any) -> Any:
    # [1] Drop every price or cost property (D-27) and its `required` entry, at any depth
    if isinstance(node, list):
        return [without_priced(item) for item in cast('list[Any]', node)]
    if not isinstance(node, dict):
        return node
    copy: dict[str, Any] = {key: without_priced(value) for key, value in cast('dict[str, Any]', node).items()}
    if isinstance(copy.get('properties'), dict):
        copy['properties'] = {k: v for k, v in copy['properties'].items() if not PRICED.search(k)}
    if isinstance(copy.get('required'), list):
        copy['required'] = [k for k in copy['required'] if not PRICED.search(str(k))]
    schemas = copy.get('schemas')
    if isinstance(schemas, dict):
        copy['schemas'] = {k: v for k, v in cast('dict[str, Any]', schemas).items() if not PRICED_SCHEMA.search(k)}
    return copy


def refs(node: Any) -> list[str]:
    if isinstance(node, list):
        return [r for item in cast('list[Any]', node) for r in refs(item)]
    if not isinstance(node, dict):
        return []
    found: list[str] = []
    for key, value in cast('dict[str, Any]', node).items():
        if key == '$ref' and isinstance(value, str):
            found.append(value)
        else:
            found.extend(refs(value))
    return found


def filtered_admin(admin: Any) -> Any:
    # [2] Filter, then prove no priced schema is still referenced
    result = without_priced(admin)
    dangling = [r for r in refs(result) if PRICED_SCHEMA.search(r.rsplit('/', 1)[-1])]
    if dangling:
        raise SystemExit(f'Priced schemas are still referenced after filtering: {sorted(set(dangling))}')
    return result


def generate(source: Path, target: Path) -> None:
    subprocess.run(
        [
            sys.executable,
            '-m',
            'datamodel_code_generator',
            '--input',
            str(source),
            '--input-file-type',
            'openapi',
            '--output',
            str(target),
            '--output-model-type',
            'typing.TypedDict',
            '--target-python-version',
            '3.10',
            '--use-union-operator',
            '--use-standard-collections',
            '--enum-field-as-literal',
            'all',
            '--disable-timestamp',
            '--formatters',
            'black',
            'isort',
        ],
        check=True,
    )
    target.write_text(HEADER + target.read_text(encoding='utf-8').replace('\r\n', '\n'), encoding='utf-8', newline='\n')


def build(into: Path) -> dict[str, str]:
    # [3] Public as pinned; admin from a price-filtered copy
    into.mkdir(parents=True, exist_ok=True)
    generate(ROOT / 'spec' / 'meridian-public.json', into / 'public.py')
    admin = json.loads((ROOT / 'spec' / 'meridian-admin.json').read_text(encoding='utf-8'))
    filtered = into / 'admin-filtered.json'
    filtered.write_text(json.dumps(filtered_admin(admin)), encoding='utf-8')
    generate(filtered, into / 'admin.py')
    filtered.unlink()

    source = json.loads((ROOT / 'spec' / 'SOURCE.json').read_text(encoding='utf-8'))
    version = (
        "__version__ = '0.0.0'\n"
        f"ENGINE_SPEC_COMMIT = '{source['engineCommit']}'\n"
        f"ENGINE_API_VERSION = '{source['publicVersion']}'\n"
    )
    return {
        '__init__.py': HEADER,
        'public.py': (into / 'public.py').read_text(encoding='utf-8'),
        'admin.py': (into / 'admin.py').read_text(encoding='utf-8'),
        '../_version.py': version,
    }


def main() -> None:
    check = '--check' in sys.argv
    with tempfile.TemporaryDirectory() as tmp:
        fresh = build(Path(tmp))
    stale: list[str] = []
    for name, text in fresh.items():
        path = (OUT / name).resolve()
        current = path.read_text(encoding='utf-8').replace('\r\n', '\n') if path.exists() else None
        if check:
            if current != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    if stale:
        print('Generated types are stale: ' + ', '.join(stale) + '. Run: uv run python scripts/generate_types.py')
        sys.exit(1)
    if not check:
        (OUT / '__init__.py').write_text(HEADER, encoding='utf-8', newline='\n')
        print('Generated types written.')


if __name__ == '__main__':
    main()
